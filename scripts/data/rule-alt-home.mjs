// Rule the regular off-campus home fields of the Howell era (FIRST_SEASON-1977)
// into data/ref/alt-home.json's "howellEra" block.
//
// Howell writes "vs." on both teams' pages for every off-campus game, so he
// never says whose home game it was. The rule: a city is a team's regular
// home field when it is in the team's own state and the team played at least
// MIN_GAMES regular-season games there against at least MIN_OPPONENTS
// different opponents. The opponent count keeps a one-rivalry neutral site
// from qualifying. build-payload.mjs then calls a game at such a city a home
// game for the team whose field it is, and neutral when both teams (or
// neither) claim the city: the Iron Bowl in Birmingham, Ole Miss-Mississippi
// State in Jackson. The exceptions below are annual neutral-site series the
// rule would otherwise hand to one side. The 1978+ rulings ("pairs") also
// apply to this era.
//
// Run after parse-jhowell.mjs and gen-team-info.mjs; prints the ruled pairs.

import fs from 'node:fs';
import path from 'node:path';
import { ROOT } from '../lib/util.mjs';
import { FIRST_SEASON } from '../lib/window.mjs';

const MIN_GAMES = 5;
const MIN_OPPONENTS = 3;
const EXCEPTIONS = [
  { teams: ['florida', 'georgia'], city: 'Jacksonville FL', reason: 'the Florida-Georgia game, a neutral-site series in Jacksonville since 1933' },
  { teams: ['army', 'notre-dame'], city: 'Bronx NY', reason: 'Army-Notre Dame at Yankee Stadium (1925-1946), a neutral-site series' },
  { teams: ['arkansas', 'lsu'], city: 'Shreveport LA', reason: 'Arkansas-LSU at the State Fair in Shreveport, a neutral-site series' },
];

const file = path.join(ROOT, 'data', 'ref', 'alt-home.json');
const doc = JSON.parse(fs.readFileSync(file, 'utf8'));
const { games } = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'build', 'jhowell.json'), 'utf8'));
const info = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'ref', 'team-info.json'), 'utf8')).teams;

const tally = new Map();
for (const r of games) {
  if (r.se < FIRST_SEASON || r.se >= 1978 || !r.city) continue;
  if (/\bbowl\b|classic|championship|playoff/i.test(r.note)) continue;
  const city = r.city.replace(/^@\s*/, '').replace(/,/g, '').trim();
  if (info[r.team]?.state !== city.slice(-2)) continue;
  const k = `${r.team}|${city}`;
  const t = tally.get(k) ?? { games: 0, opps: new Set() };
  t.games++;
  t.opps.add(r.opp);
  tally.set(k, t);
}
const pairs = {};
const lines = [];
for (const [k, t] of [...tally].sort((a, b) => b[1].games - a[1].games)) {
  if (t.games < MIN_GAMES || t.opps.size < MIN_OPPONENTS) continue;
  const [team, city] = k.split('|');
  (pairs[team] ??= []).push(city);
  lines.push(`${team} ${city}: ${t.games} games, ${t.opps.size} opponents`);
}
doc.howellEra = {
  note: `Regular off-campus home fields for ${FIRST_SEASON}-1977, generated by scripts/data/rule-alt-home.mjs (the rule is in its header): in the team's state, ${MIN_GAMES}+ regular-season games against ${MIN_OPPONENTS}+ opponents. A game at a city both teams claim, or neither, is neutral; so is every game in 'exceptions'. The 1978+ 'pairs' also apply to this era.`,
  pairs: Object.fromEntries(Object.entries(pairs).sort()),
  exceptions: EXCEPTIONS,
};
fs.writeFileSync(file, JSON.stringify(doc, null, 2) + '\n');
console.log(`howell-era home fields: ${lines.length} (team, city) pairs\n  ${lines.join('\n  ')}`);
